use super::{num, ExportOptions, Item};
use crate::color::hex;
use crate::geom::{Path, Seg, VectorImage};
use std::fmt::Write;

pub fn path_data(paths: &[&Path]) -> String {
    let mut d = String::new();
    for p in paths {
        let _ = write!(d, "M{} {}", num(p.start.x), num(p.start.y));
        for s in &p.segs {
            match *s {
                Seg::Line(e) => {
                    let _ = write!(d, "L{} {}", num(e.x), num(e.y));
                }
                Seg::Cubic(a, b, e) => {
                    let _ = write!(d, "C{} {} {} {} {} {}", num(a.x), num(a.y), num(b.x), num(b.y), num(e.x), num(e.y));
                }
            }
        }
        d.push('Z');
    }
    d
}

pub fn write(img: &VectorImage, items: &[Item], opt: &ExportOptions) -> String {
    let mut s = String::new();
    let _ = writeln!(s, r#"<?xml version="1.0" encoding="UTF-8"?>"#);
    let _ = writeln!(
        s,
        r#"<svg xmlns="http://www.w3.org/2000/svg" version="1.1" width="{w}pt" height="{h}pt" viewBox="0 0 {w} {h}">"#,
        w = img.width,
        h = img.height
    );
    let _ = writeln!(s, "<!-- Generated by Vector Free -->");
    for it in items {
        let c = hex(it.rgb);
        let stroke = if opt.stroke {
            format!(r#" stroke="{c}" stroke-width="{}" stroke-linejoin="round""#, num(opt.stroke_width))
        } else {
            String::new()
        };
        let opacity = if it.alpha < 255 { format!(r#" opacity="{}""#, num(it.alpha as f64 / 255.0)) } else { String::new() };
        let _ = writeln!(s, r#"<path fill="{c}" fill-rule="evenodd"{opacity}{stroke} d="{}"/>"#, path_data(&it.paths));
    }
    s.push_str("</svg>\n");
    s
}
